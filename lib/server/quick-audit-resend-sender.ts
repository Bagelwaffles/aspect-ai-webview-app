/**
 * Resend Preview-only sending adapter.
 *
 * No route, scheduler, or customer sender is enabled. A domain-restricted,
 * sending-only credential is the ONLY Resend credential held by this worker.
 * Independently obtained provider verification proof is injected through a
 * read-only source (see quick-audit-resend-domain-proof.ts).
 */
import { createHash } from "node:crypto"
import {
  AMS_CUSTOMER_FROM_ADDRESS,
  AMS_CUSTOMER_FROM_NAME,
  type QuickAuditTransactionalSender,
} from "./quick-audit-delivery-worker"
import {
  AMS_RESEND_DOMAIN_ID,
  hasCurrentResendDomainProof,
  type ResendVerifiedDomainProof,
} from "./quick-audit-resend-domain-proof"

const BASE_URL = "https://api.resend.com"
const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

type ResendSenderOptions = {
  env?: NodeJS.ProcessEnv
  fetcher?: typeof fetch
  /** Independent protected proof from an owner-only domain API check. */
  readDomainProof: () => Promise<ResendVerifiedDomainProof | null>
  now?: () => Date
}

export function createResendAuditSender({
  env = process.env,
  fetcher = fetch,
  readDomainProof,
  now = () => new Date(),
}: ResendSenderOptions): QuickAuditTransactionalSender {
  const sendOnlyToken = env.AMS_RESEND_SEND_API_KEY?.trim()
  const domainId = env.AMS_RESEND_DOMAIN_ID?.trim()
  if (!sendOnlyToken || !domainId || domainId !== AMS_RESEND_DOMAIN_ID ||
      !readDomainProof || env.VERCEL_ENV !== "preview" ||
      env.AMS_QUICK_AUDIT_DELIVERY_SEND_ENABLED !== "true") {
    throw new Error("AMS_RESEND_SENDER_NOT_CONFIGURED")
  }

  const inspectSender: QuickAuditTransactionalSender["inspectSender"] = async (address) => {
    if (address.trim().toLowerCase() !== AMS_CUSTOMER_FROM_ADDRESS) return null
    // The send-only key CANNOT read Resend domain status. This independent
    // evidence is generated by an owner-authorized admin-only verification,
    // which is never called or refreshed by this sender.
    let proof: ResendVerifiedDomainProof | null
    try {
      proof = await readDomainProof()
    } catch {
      return null
    }
    if (!hasCurrentResendDomainProof(proof, now())) return null
    return {
      address: AMS_CUSTOMER_FROM_ADDRESS,
      displayName: AMS_CUSTOMER_FROM_NAME,
      replyToAddress: AMS_CUSTOMER_FROM_ADDRESS,
      verificationStatus: "accepted",
    }
  }

  return {
    inspectSender,
    async send(input) {
      if (input.fromAddress !== AMS_CUSTOMER_FROM_ADDRESS ||
          input.fromName !== AMS_CUSTOMER_FROM_NAME ||
          input.replyToAddress !== AMS_CUSTOMER_FROM_ADDRESS ||
          !input.recipient.trim() ||
          !input.subject.trim() ||
          !input.plainText.trim()) {
        throw new Error("AMS_BUSINESS_SENDER_IDENTITY_REQUIRED")
      }
      if (!(await inspectSender(AMS_CUSTOMER_FROM_ADDRESS))) {
        throw new Error("AMS_RESEND_DOMAIN_NOT_VERIFIED")
      }
      const idempotencyKey = "ams-audit-" + createHash("sha256")
        .update(JSON.stringify({
          recipient: input.recipient.toLowerCase(),
          subject: input.subject,
          content: input.plainText,
        })).digest("hex")
      const response = await fetcher(`${BASE_URL}/emails`, {
        method: "POST",
        headers: {
          Authorization: `Bearer ${sendOnlyToken}`,
          "Content-Type": "application/json",
          "Idempotency-Key": idempotencyKey,
        },
        body: JSON.stringify({
          from: `${AMS_CUSTOMER_FROM_NAME} <${AMS_CUSTOMER_FROM_ADDRESS}>`,
          to: [input.recipient],
          reply_to: AMS_CUSTOMER_FROM_ADDRESS,
          subject: input.subject,
          text: input.plainText,
        }),
        redirect: "error",
        cache: "no-store",
        signal: AbortSignal.timeout(10_000),
      })
      if (!response.ok) throw new Error("AMS_RESEND_SEND_UNCONFIRMED")
      const data: unknown = await response.json().catch(() => null)
      if (!data || typeof data !== "object" ||
          typeof (data as { id?: unknown }).id !== "string" ||
          !uuid.test((data as { id: string }).id)) {
        throw new Error("AMS_RESEND_ACCEPTANCE_UNCONFIRMED")
      }
      return {
        messageId: (data as { id: string }).id,
        // Provider response does not prove recipient view or delivered header.
        fromAddress: AMS_CUSTOMER_FROM_ADDRESS,
      }
    },
  }
}
